//! `cargo xtask wasm`: build the viewer and bundle it into `crates/mdbook-reef/assets/reef.js`.
//!
//! The bundle is wasm-bindgen's `no-modules` glue, the wasm itself base64-encoded, and a few
//! lines that start it. One classic script, so it loads from `additional-js` like any other
//! and works from `file://` too, where fetching a separate `.wasm` would not.

use anyhow::{Context, Result, bail};
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() -> Result<()> {
    let task = std::env::args().nth(1).unwrap_or_default();
    match task.as_str() {
        "wasm" => wasm(),
        _ => bail!("usage: cargo xtask wasm"),
    }
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .to_path_buf()
}

fn run(cmd: &mut Command) -> Result<()> {
    eprintln!("$ {cmd:?}");
    let status = cmd.status().with_context(|| format!("running {cmd:?}"))?;
    if !status.success() {
        bail!("{cmd:?} failed: {status}");
    }
    Ok(())
}

/// The wasm features the viewer is built for: rustc's defaults for wasm32-unknown-unknown, which
/// dx builds the app's copy with too, given to wasm-opt so it keeps them
const WASM_FEATURES: [&str; 6] = [
    "--enable-bulk-memory",
    "--enable-multivalue",
    "--enable-mutable-globals",
    "--enable-nontrapping-float-to-int",
    "--enable-reference-types",
    "--enable-sign-ext",
];

/// Builds the viewer, binds it, and writes the bundle the books load
///
/// The build ignores the caller's `RUSTFLAGS`, so `reef.js` is the same from any shell. An
/// exported `-Ctarget-cpu=native` would leave wasm32 with no target features at all, and the glue
/// without its externref table.
fn wasm() -> Result<()> {
    let root = root();
    // no flags but rustc's defaults: the encoded variable wins over `RUSTFLAGS` and every config's
    // `rustflags`, and an empty one means none
    run(Command::new(env!("CARGO"))
        .current_dir(&root)
        .env_remove("RUSTFLAGS")
        .env("CARGO_ENCODED_RUSTFLAGS", "")
        .args([
            "build",
            "--profile",
            "wasm",
            "-p",
            "reef-view",
            "--target",
            "wasm32-unknown-unknown",
        ]))?;
    let target_dir = std::env::var_os("CARGO_TARGET_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| root.join("target"));
    let wasm = target_dir.join("wasm32-unknown-unknown/wasm/reef_view.wasm");
    let out = target_dir.join("reef-bindgen");
    std::fs::create_dir_all(&out)?;
    run(Command::new("wasm-bindgen")
        .args([
            "--target",
            "no-modules",
            "--no-typescript",
            "--out-name",
            "reef",
        ])
        .arg("--out-dir")
        .arg(&out)
        .arg(&wasm))
    .context("is wasm-bindgen-cli installed? `cargo install wasm-bindgen-cli --version 0.2.130`")?;
    let mut bg = out.join("reef_bg.wasm");
    // Shrink it if wasm-opt is around; it is optional.
    let opt = out.join("reef_opt.wasm");
    if Command::new("wasm-opt").arg("--version").output().is_ok() {
        run(Command::new("wasm-opt")
            .arg("-Os")
            .args(WASM_FEATURES)
            .arg(&bg)
            .arg("-o")
            .arg(&opt))?;
        bg = opt;
    }
    let glue = std::fs::read_to_string(out.join("reef.js"))?;
    let bytes = std::fs::read(&bg)?;
    let js = format!(
        "/* reef {} - planning graphs for mdbook. Generated by `cargo xtask wasm`; do not edit. */\n(function () {{\n{glue}\nconst bytes = Uint8Array.from(atob(\"{}\"), c => c.charCodeAt(0));\nwasm_bindgen.initSync({{ module: bytes }});\n}})();\n",
        env!("CARGO_PKG_VERSION"),
        base64(&bytes)
    );
    let dest = root.join("crates/mdbook-reef/assets/reef.js");
    std::fs::write(&dest, js)?;
    eprintln!(
        "wrote {} ({} KiB wasm, {} KiB bundle)",
        dest.display(),
        bytes.len() / 1024,
        std::fs::metadata(&dest)?.len() / 1024
    );
    Ok(())
}

fn base64(data: &[u8]) -> String {
    const T: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut s = String::with_capacity(data.len().div_ceil(3) * 4);
    for c in data.chunks(3) {
        let n = (c[0] as u32) << 16
            | (*c.get(1).unwrap_or(&0) as u32) << 8
            | *c.get(2).unwrap_or(&0) as u32;
        s.push(T[(n >> 18) as usize & 63] as char);
        s.push(T[(n >> 12) as usize & 63] as char);
        s.push(if c.len() > 1 {
            T[(n >> 6) as usize & 63] as char
        } else {
            '='
        });
        s.push(if c.len() > 2 {
            T[n as usize & 63] as char
        } else {
            '='
        });
    }
    s
}
